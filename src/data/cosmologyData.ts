// Helper to generate gate timing and degree coords
function g(
  id: number,
  actNumber: number,
  qIdx: number,
  sign: any,
  element: any,
  angelName: string,
  angelHebrew: string,
  angelChoir: string,
  angelSphere: string,
  angelFreq: number,
  angelAttr: string,
  demonName: string,
  demonGoetia: number,
  demonRank: string,
  demonLegions: number,
  demonMetal: string,
  demonFreq: number,
  demonTitle: string,
  interaction: string,
  isBreach: boolean = false
): GateData {
  const startDegree = (id - 1) * 5;
  const endDegree = id * 5;
  const startTime = (id - 1) * (600 / 72);
  const endTime = id * (600 / 72);
  const decanIndex = Math.floor(((startDegree % 30) / 10)) + 1;

  return {
    id,
    actNumber,
    startDegree,
    endDegree,
    startTime,
    endTime,
    sign,
    decanIndex,
    quinanceIndex: qIdx,
    element,
    angel: {
      name: angelName,
      hebrew: angelHebrew,
      choir: angelChoir,
      sphere: angelSphere,
      frequencyHz: angelFreq,
      divineAttribute: angelAttr,
      lightManifestation: `${angelName} emanates pure ${element.toLowerCase()} light frequency (${angelFreq}Hz)`,
    },
    demon: {
      name: demonName,
      goetiaNumber: demonGoetia,
      rank: demonRank,
      legions: demonLegions,
      metal: demonMetal,
      frequencyHz: demonFreq,
      chthonicTitle: demonTitle,
      shadowManifestation: `${demonName} anchors chthonic resonance (${demonFreq}Hz) commanding ${demonLegions} legions`,
    },
    harmonicInteraction: interaction,
    isBreachPoint: isBreach,
  };
}

